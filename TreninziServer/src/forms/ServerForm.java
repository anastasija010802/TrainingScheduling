    private void miStartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_miStartActionPerformed
         if (threadServer == null || !threadServer.isAlive()) {
            threadServer = new ThreadServer();
            threadServer.start();
            JOptionPane.showMessageDialog(this, "Pokretanje servera...");
                   lblStatus.setText("RUNNING");
            miStop.setEnabled(true);
            miStart.setEnabled(false);
            lblStatus.setBackground(Color.GREEN);
 
        }
    }//GEN-LAST:event_miStartActionPerformed

    private void miStopActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_miStopActionPerformed
         if (threadServer.getServerSocket() != null && threadServer.getServerSocket().isBound()) {
            try {
                threadServer.getServerSocket().close();
                JOptionPane.showMessageDialog(this, "Gasenje servera...");
                miStart.setEnabled(true);
                miStop.setEnabled(false);
                lblStatus.setText("STOPPED");
                lblStatus.setBackground(Color.red);
            } catch (IOException ex) {
                Logger.getLogger(ServerForm.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_miStopActionPerformed

