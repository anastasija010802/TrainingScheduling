    private void btnDetaljiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDetaljiActionPerformed
        int row= tblTreninzi.getSelectedRow();
        if (row>=0) {
            TableModelTreninzi model= (TableModelTreninzi) tblTreninzi.getModel();
            Trening t=model.getTrening(row);
            (new FormDetaljiTreninga(this, true,t)).setVisible(true);
        }
    }//GEN-LAST:event_btnDetaljiActionPerformed

