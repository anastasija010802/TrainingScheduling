    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed
        if (txtOpis.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Sva polja moraju biti popunjena");
            return;
        }
        try{
        
           t.setOpis(txtOpis.getText());
        ClientController.getInstance().updateTrening(t);
        FormPretragaTreninga fpt= (FormPretragaTreninga) getParent();
        fpt.refresTable();
        JOptionPane.showMessageDialog(this, "Uspesno izmenjen trening");
        this.dispose();
        }
        catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
//            Logger.getLogger(FormDetaljiKlijenta.class.getName()).log(Level.SEVERE, null, ex);
        }
     
    }//GEN-LAST:event_btnIzmeniActionPerformed

    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed
        int result= JOptionPane.showConfirmDialog(this, "Da li ste sigurni da zelite da obrisete ovaj trening?");
        if (result== JOptionPane.YES_OPTION) {
            try {
                ClientController.getInstance().deleteTrening(t);
                FormPretragaTreninga fpt= (FormPretragaTreninga) getParent();
                fpt.refresTable();
                JOptionPane.showMessageDialog(this, "Uspesno obrisan trening");
                this.dispose();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Ne mozete da obrisete ovaj trening jer ima program");
            }
        }
        if (result== JOptionPane.NO_OPTION) {
            return;
        }
    }//GEN-LAST:event_btnObrisiActionPerformed

