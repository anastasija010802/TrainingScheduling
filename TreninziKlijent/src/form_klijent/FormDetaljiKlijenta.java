    private void popuniFitnesProfile() {
        try {
            ArrayList<FitnesProfil> profili = ClientController.getInstance()
                    .getAllFitnesProfil(new FitnesProfil(0, ""));

            cmbFitnes.removeAllItems();

            for (FitnesProfil fitnesProfil : profili) {
                cmbFitnes.addItem(fitnesProfil);
            }

        } catch (Exception ex) {
            Logger.getLogger(FormNoviKlijent.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    private void popuniPrograme() {
 try { 
            ArrayList<Program> programi = ClientController.getInstance().getAllProgram(new Program(0, null, null, "", 0, k, new Trener(0, "", "", "", ""), null)) ;

            cmbProgrami.removeAllItems();

            for (Program program : programi) {
                cmbProgrami.addItem(program);
            }

        } catch (Exception ex) {
            Logger.getLogger(FormNoviKlijent.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

